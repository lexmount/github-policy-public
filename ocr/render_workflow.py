"""Embed the tested client; required workflows must not load target PR scripts."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = '''# Generated by python3 ocr/render_workflow.py; edit ocr/ci_client.py.
name: OCR Code Review

on:
  pull_request_target:

permissions: {}

concurrency:
  group: ocr-org-${{ github.repository }}-${{ github.event.pull_request.number }}
  cancel-in-progress: true

jobs:
  ocr-review:
    name: OCR dispatch
    runs-on: ubuntu-latest
    timeout-minutes: 3
    steps:
      - name: Submit PR and confirm durable acceptance (90 seconds maximum)
        env:
          OCR_CI_TOKEN: ${{ secrets.OCR_CI_TOKEN }}
        shell: bash
        run: |
          python3 - <<'OCR_PY'
'''

def rendered():
    source = (ROOT / 'ocr/ci_client.py').read_text()
    return HEADER + ''.join(('          ' + line if line else '') + '\n' for line in source.splitlines()) + '          OCR_PY\n'

if __name__ == '__main__':
    (ROOT / '.github/workflows/codex-code-review.yml').write_text(rendered())
